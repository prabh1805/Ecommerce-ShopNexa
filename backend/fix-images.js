// Update all products per category
for (const [category, urls] of Object.entries(imageMap)) {
  const products = db.products.find({ category: category }).sort({ _id: 1 }).toArray();
  let updated = 0;
  for (let i = 0; i < products.length; i++) {
    const url = urls[i % urls.length];
    db.products.updateOne({ _id: products[i]._id }, { $set: { imageUrl: url } });
    updated++;
  }
  print("✅ " + category + ": updated " + updated + " product images");
}

